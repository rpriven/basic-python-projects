    print("        self.age = age")
    print("    ")
    print("    # Instance method")
    print("    def greet(self):")
    print("        return f'Hello, my name is {self.name}'")
    print("    ")
    print("    # String representation")
    print("    def __str__(self):")
    print("        return f'Person: {self.name}, {self.age} years old'")
    
    choice = display_continue_menu()
    if choice == "1":
        print("\nCreating and Using Objects:")
        print("# Create instances of the class")
        print("person1 = Person('Alice', 30)")
