        print("person1.name                # 'Alice'")
        print("person1.age                 # 30")
        print("person1.species             # 'Human'")
        print("person1.greet()             # 'Hello, my name is Alice'")
        print("print(person1)              # 'Person: Alice, 30 years old'")
        print("\n# Modifying attributes")
        print("person1.age = 31            # Change instance attribute")
        print("Person.species = 'Homosapien'  # Change class attribute for all instances")
        
        choice = display_continue_menu()
