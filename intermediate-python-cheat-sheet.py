def display_decorators():
    print("\n" + "=" * 60)
    print("DECORATORS".center(60))
    print("=" * 60)
    
    print("\nBasic Decorator:")
    print("def my_decorator(func):")
    print("    def wrapper():")
    print("        print('Something before the function call')")
    print("        func()")
    print("        print('Something after the function call')")
    print("    return wrapper")
    print("\n# Using the decorator")
    print("@my_decorator")
    print("def say_hello():")
    print("    print('Hello!')")
    print("\n# Equivalent to: say_hello = my_decorator(say_hello)")
    print("# Calling the decorated function")
    print("say_hello()")
    
    choice = display_continue_menu()
    if choice == "1":
        print("\nDecorators with Arguments:")
        print("def my_decorator(func):")
        print("    def wrapper(*args, **kwargs):")
        print("        print('Before function call')")
        print("        result = func(*args, **kwargs)")
        print("        print('After function call')")
        print("        return result")
        print("    return wrapper")
        print("\n@my_decorator")
        print("def add(a, b):")
        print("    return a + b")
        print("\n# Now add can take arguments")
        print("result = add(3, 5)  # Returns 8")
        print("\nDecorators with Parameters:")
        print("def repeat(n):")
        print("    def decorator(func):")
        print("        def wrapper(*args, **kwargs):")
        print("            results = []")
        print("            for _ in range(n):")
        print("                results.append(func(*args, **kwargs))")
        print("            return results")
        print("        return wrapper")
        print("    return decorator")
        
        choice = display_continue_menu()
        if choice == "1":
            print("\n# Using parameterized decorator")
            print("@repeat(3)")
            print("def greet(name):")
            print("    return f'Hello, {name}!'")
            print("\n# Calls greet('Alice') three times and returns the results as a list")
            print("results = greet('Alice')  # ['Hello, Alice!', 'Hello, Alice!', 'Hello, Alice!']")
            print("\nPractical Decorator Examples:")
            print("# Timing decorator")
            print("import time")
            print("def timing_decorator(func):")
            print("    def wrapper(*args, **kwargs):")
            print("        start_time = time.time()")
            print("        result = func(*args, **kwargs)")
            print("        end_time = time.time()")
            print("        print(f'Function {func.__name__} took {end_time - start_time:.4f} seconds')")
            print("        return result")
            print("    return wrapper")
            print("\n# Memoization decorator (caching)")
            print("def memoize(func):")
            print("    cache = {}")
            print("    def wrapper(*args):")
            print("        if args not in cache:")
            print("            cache[args] = func(*args)")
            print("        return cache[args]")
            print("    return wrapper")

